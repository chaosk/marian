CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discord_id TEXT NOT NULL UNIQUE
);

INSERT INTO accounts (discord_id)
SELECT DISTINCT discord_id
FROM users
WHERE discord_id IS NOT NULL AND btrim(discord_id) <> '';

ALTER TABLE users ADD COLUMN account_id BIGINT REFERENCES accounts(id) ON DELETE CASCADE;

UPDATE users AS membership
SET account_id = accounts.id
FROM accounts
WHERE membership.discord_id = accounts.discord_id;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM users WHERE account_id IS NULL) THEN
    RAISE EXCEPTION 'A membership has no Discord account';
  END IF;
END $$;

ALTER TABLE users ALTER COLUMN account_id SET NOT NULL;
ALTER TABLE users DROP COLUMN discord_id;
