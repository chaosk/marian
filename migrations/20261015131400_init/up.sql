CREATE TABLE meta (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE guilds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  timezone TEXT NOT NULL,
  discord_id TEXT
);

CREATE TABLE settings (
  guild_id BIGINT PRIMARY KEY REFERENCES guilds(id) ON DELETE CASCADE,
  default_reminder_minutes BIGINT NOT NULL DEFAULT 15,
  thread_reminders BOOLEAN NOT NULL DEFAULT TRUE,
  auto_archive BOOLEAN NOT NULL DEFAULT TRUE,
  auto_archive_hours BIGINT NOT NULL DEFAULT 12,
  event_threads BOOLEAN NOT NULL DEFAULT TRUE,
  auto_join_threads BOOLEAN NOT NULL DEFAULT TRUE,
  show_attendees BOOLEAN NOT NULL DEFAULT TRUE,
  hour_24 BOOLEAN NOT NULL DEFAULT FALSE,
  localize_time BOOLEAN NOT NULL DEFAULT TRUE,
  purge_channels BOOLEAN NOT NULL DEFAULT FALSE,
  temp_roles BOOLEAN NOT NULL DEFAULT FALSE,
  calendar_auto_sync BOOLEAN NOT NULL DEFAULT TRUE,
  role_event BIGINT,
  role_edit BIGINT,
  role_delete BIGINT,
  role_channel BIGINT,
  role_signup BIGINT,
  post_lead_hours BIGINT NOT NULL DEFAULT 48,
  digest TEXT NOT NULL DEFAULT 'off',
  park_clock BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  color TEXT NOT NULL,
  discord_id TEXT
);

CREATE TABLE channels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'text',
  position BIGINT NOT NULL DEFAULT 0,
  purged_at TEXT,
  discord_id TEXT
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  handle TEXT NOT NULL,
  color TEXT NOT NULL,
  reminders_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  organizer BOOLEAN NOT NULL DEFAULT FALSE,
  discord_id TEXT,
  UNIQUE (guild_id, handle)
);

CREATE TABLE user_roles (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, role_id)
);

CREATE TABLE event_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  channel_id BIGINT NOT NULL REFERENCES channels(id),
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  duration_minutes BIGINT NOT NULL,
  color TEXT NOT NULL DEFAULT '#1e3a6e',
  image_url TEXT,
  thread_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  multiple_signups BOOLEAN NOT NULL DEFAULT FALSE,
  mention_everyone BOOLEAN NOT NULL DEFAULT FALSE,
  attendee_role_id BIGINT REFERENCES roles(id) ON DELETE SET NULL,
  cutoff_offset_minutes BIGINT,
  options_json TEXT NOT NULL DEFAULT '[]',
  reminders_json TEXT NOT NULL DEFAULT '[]',
  mention_role_ids TEXT NOT NULL DEFAULT '[]',
  restrict_role_ids TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL
);

CREATE TABLE series (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id TEXT NOT NULL,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  cadence TEXT NOT NULL,
  end_on TEXT,
  max_occurrences BIGINT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  template_id BIGINT NOT NULL REFERENCES event_templates(id),
  anchor_start TEXT NOT NULL,
  post_lead_hours BIGINT NOT NULL DEFAULT 48,
  created_at TEXT NOT NULL
);

CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id TEXT NOT NULL,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  channel_id BIGINT NOT NULL REFERENCES channels(id),
  series_id BIGINT REFERENCES series(id) ON DELETE SET NULL,
  occurrence_index BIGINT,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  starts_at TEXT NOT NULL,
  duration_minutes BIGINT NOT NULL DEFAULT 60,
  status TEXT NOT NULL,
  post_at TEXT,
  posted_at TEXT,
  archived_at TEXT,
  color TEXT NOT NULL DEFAULT '#1e3a6e',
  image_url TEXT,
  cutoff_at TEXT,
  mention_everyone BOOLEAN NOT NULL DEFAULT FALSE,
  attendee_role_id BIGINT REFERENCES roles(id) ON DELETE SET NULL,
  thread_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  multiple_signups BOOLEAN NOT NULL DEFAULT FALSE,
  created_by BIGINT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  calendar_synced_at TEXT,
  signups_closed BOOLEAN NOT NULL DEFAULT FALSE,
  post_attempts BIGINT NOT NULL DEFAULT 0,
  discord_message_id TEXT
);

CREATE TABLE event_roles (
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  PRIMARY KEY (event_id, role_id, kind)
);

CREATE TABLE signup_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  emoji TEXT NOT NULL,
  capacity BIGINT,
  waitlist BOOLEAN NOT NULL DEFAULT FALSE,
  role_id BIGINT,
  reminders_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  position BIGINT NOT NULL
);

CREATE TABLE signups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  option_id BIGINT NOT NULL REFERENCES signup_options(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  state TEXT NOT NULL,
  created_at TEXT NOT NULL,
  UNIQUE (option_id, user_id)
);

CREATE TABLE reminders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  offset_minutes BIGINT NOT NULL,
  message TEXT NOT NULL DEFAULT '',
  sent_at TEXT
);

CREATE TABLE threads (
  event_id BIGINT PRIMARY KEY REFERENCES events(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  discord_id TEXT
);

CREATE TABLE applied_access (
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  discord_user_id TEXT NOT NULL,
  kind TEXT NOT NULL,
  PRIMARY KEY (event_id, discord_user_id, kind)
);

CREATE TABLE thread_members (
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (event_id, user_id)
);

CREATE TABLE thread_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  body TEXT NOT NULL,
  place TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE role_grants (
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  PRIMARY KEY (event_id, user_id)
);

CREATE TABLE presets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id TEXT NOT NULL,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  body TEXT NOT NULL
);

CREATE TABLE option_library (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  emoji TEXT NOT NULL,
  UNIQUE (guild_id, name)
);

CREATE TABLE activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  event_id BIGINT REFERENCES events(id) ON DELETE SET NULL,
  body TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE command_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL,
  line TEXT NOT NULL,
  reply TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE event_prompts (
  discord_user_id TEXT PRIMARY KEY,
  guild_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  step TEXT NOT NULL,
  title TEXT,
  start_raw TEXT,
  channel_name TEXT,
  source_channel TEXT,
  source_discord TEXT,
  draft TEXT
);

CREATE TABLE web_sessions (
  token TEXT PRIMARY KEY,
  discord_user_id TEXT NOT NULL,
  display_name TEXT NOT NULL,
  guild_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE web_session_guilds (
  token TEXT NOT NULL REFERENCES web_sessions(token) ON DELETE CASCADE,
  guild_id BIGINT NOT NULL,
  PRIMARY KEY (token, guild_id)
);

CREATE TABLE calendar_feeds (
  token TEXT PRIMARY KEY,
  discord_user_id TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL
);

CREATE TABLE routines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id TEXT NOT NULL,
  guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  template_id BIGINT NOT NULL REFERENCES event_templates(id),
  prompt TEXT NOT NULL,
  start_minutes BIGINT NOT NULL,
  poll_weekday BIGINT NOT NULL,
  poll_minutes BIGINT NOT NULL,
  lock_weekday BIGINT NOT NULL,
  lock_minutes BIGINT NOT NULL,
  days_json TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_by BIGINT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX idx_routines_public_id ON routines (public_id);

CREATE TABLE routine_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  routine_id BIGINT NOT NULL REFERENCES routines(id) ON DELETE CASCADE,
  opens_at TEXT NOT NULL,
  locks_at TEXT NOT NULL,
  status TEXT NOT NULL,
  days_json TEXT NOT NULL,
  winner_weekday BIGINT,
  event_id BIGINT REFERENCES events(id) ON DELETE SET NULL,
  discord_message_id TEXT,
  created_at TEXT NOT NULL
);

CREATE UNIQUE INDEX idx_routine_runs_window ON routine_runs (routine_id, opens_at);

CREATE TABLE routine_votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES routine_runs(id) ON DELETE CASCADE,
  choice TEXT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  UNIQUE (run_id, user_id, choice)
);

CREATE UNIQUE INDEX idx_events_public_id ON events (public_id);
CREATE UNIQUE INDEX idx_series_public_id ON series (public_id);
CREATE UNIQUE INDEX idx_presets_public_id ON presets (public_id);
CREATE INDEX idx_events_guild_status ON events (guild_id, status, starts_at);
CREATE INDEX idx_events_series ON events (series_id, occurrence_index);
CREATE INDEX idx_signups_event ON signups (event_id, option_id, state);
CREATE INDEX idx_activity_guild ON activity (guild_id, id);
