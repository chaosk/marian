-- Attendance types live in each server's library. An event's options, a
-- preset's types, and a series or routine template's types point at library
-- entries and keep only what is theirs: order, capacity, and role limit.
-- Name, emoji, and whether the type counts as attending belong to the entry.

ALTER TABLE option_library
  ADD COLUMN public_id uuid NOT NULL DEFAULT marian_uuid_v7(),
  ADD COLUMN attending boolean NOT NULL DEFAULT false;

-- One entry per name in a server, whatever the case.
DELETE FROM option_library a
  USING option_library b
  WHERE a.guild_id = b.guild_id AND lower(a.name) = lower(b.name) AND a.id > b.id;
ALTER TABLE option_library DROP CONSTRAINT option_library_guild_id_name_key;
CREATE UNIQUE INDEX idx_option_library_guild_name ON option_library (guild_id, lower(name));
CREATE UNIQUE INDEX idx_option_library_public_id ON option_library (public_id);

-- Every type in use, and the three every server starts with.
CREATE TEMP TABLE used_types ON COMMIT DROP AS
  SELECT e.guild_id, trim(o.name) AS name, o.emoji, o.reminders_enabled AS attending
    FROM signup_options o JOIN events e ON e.id = o.event_id
  UNION ALL
  SELECT p.guild_id, trim(x->>'name'), coalesce(x->>'emoji', ''), coalesce((x->>'reminders_enabled')::boolean, false)
    FROM presets p, jsonb_array_elements(coalesce(p.body->'options', '[]'::jsonb)) x
  UNION ALL
  SELECT t.guild_id, trim(x->>'name'), coalesce(x->>'emoji', ''), coalesce((x->>'reminders_enabled')::boolean, false)
    FROM event_templates t, jsonb_array_elements(t.options_json) x
  UNION ALL
  SELECT g.id, d.name, d.emoji, d.attending
    FROM guilds g,
         (VALUES ('Accepted', '✅', true), ('Declined', '❌', false), ('Tentative', '❔', false)) d (name, emoji, attending);

-- The spelling and emoji seen most often for a name, attending if it ever was.
CREATE TEMP TABLE named_types ON COMMIT DROP AS
  SELECT guild_id,
         lower(name) AS key,
         mode() WITHIN GROUP (ORDER BY name) AS name,
         mode() WITHIN GROUP (ORDER BY emoji) AS emoji,
         bool_or(attending) AS attending
    FROM used_types
   WHERE name <> ''
   GROUP BY guild_id, lower(name);

UPDATE option_library l
   SET attending = n.attending
  FROM named_types n
 WHERE n.guild_id = l.guild_id AND n.key = lower(l.name);

INSERT INTO option_library (guild_id, name, emoji, attending)
SELECT n.guild_id, n.name, CASE WHEN n.emoji = '' THEN '•' ELSE n.emoji END, n.attending
  FROM named_types n
 WHERE NOT EXISTS (
   SELECT 1 FROM option_library l WHERE l.guild_id = n.guild_id AND lower(l.name) = n.key
 );

-- Event options point at their type.
ALTER TABLE signup_options ADD COLUMN type_id bigint REFERENCES option_library (id);
UPDATE signup_options o
   SET type_id = l.id
  FROM events e, option_library l
 WHERE e.id = o.event_id AND l.guild_id = e.guild_id AND lower(l.name) = lower(trim(o.name));
ALTER TABLE signup_options
  ALTER COLUMN type_id SET NOT NULL,
  DROP COLUMN name,
  DROP COLUMN emoji,
  DROP COLUMN reminders_enabled;
CREATE INDEX idx_signup_options_type ON signup_options (type_id);

-- A preset is an ordered list of types, each with its own capacity and role limit.
CREATE TABLE preset_options (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preset_id bigint NOT NULL REFERENCES presets (id) ON DELETE CASCADE,
  type_id bigint NOT NULL REFERENCES option_library (id),
  position bigint NOT NULL,
  capacity bigint,
  role_id bigint REFERENCES roles (id) ON DELETE SET NULL
);
CREATE INDEX idx_preset_options_preset ON preset_options (preset_id, position);

ALTER TABLE presets
  ADD COLUMN multiple_signups boolean NOT NULL DEFAULT false,
  ALTER COLUMN public_id SET DEFAULT marian_uuid_v7();
UPDATE presets SET multiple_signups = coalesce((body->>'multiple_signups')::boolean, false);
INSERT INTO preset_options (preset_id, type_id, position, capacity, role_id)
SELECT p.id, l.id, x.pos - 1, (x.opt->>'capacity')::bigint,
       (SELECT r.id FROM roles r WHERE r.id = (x.opt->>'role_id')::bigint AND r.guild_id = p.guild_id)
  FROM presets p
 CROSS JOIN LATERAL jsonb_array_elements(coalesce(p.body->'options', '[]'::jsonb)) WITH ORDINALITY x (opt, pos)
  JOIN option_library l ON l.guild_id = p.guild_id AND lower(l.name) = lower(trim(x.opt->>'name'));
ALTER TABLE presets DROP COLUMN body;

-- Each server's default preset: the one a new event starts from.
ALTER TABLE settings ADD COLUMN default_preset_id bigint REFERENCES presets (id) ON DELETE SET NULL;
WITH made AS (
  INSERT INTO presets (guild_id, name, multiple_signups)
  SELECT id, 'Standard', false FROM guilds
  RETURNING id, guild_id
), types AS (
  INSERT INTO preset_options (preset_id, type_id, position)
  SELECT m.id, l.id, d.position
    FROM made m
    JOIN (VALUES ('accepted', 0), ('declined', 1), ('tentative', 2)) d (key, position) ON true
    JOIN option_library l ON l.guild_id = m.guild_id AND lower(l.name) = d.key
  RETURNING preset_id
)
UPDATE settings s SET default_preset_id = m.id FROM made m WHERE m.guild_id = s.guild_id;

-- A series or routine template keeps its types the same way.
CREATE TABLE template_options (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id bigint NOT NULL REFERENCES event_templates (id) ON DELETE CASCADE,
  type_id bigint NOT NULL REFERENCES option_library (id),
  position bigint NOT NULL,
  capacity bigint,
  role_id bigint REFERENCES roles (id) ON DELETE SET NULL
);
CREATE INDEX idx_template_options_template ON template_options (template_id, position);
INSERT INTO template_options (template_id, type_id, position, capacity, role_id)
SELECT t.id, l.id, x.pos - 1, (x.opt->>'capacity')::bigint,
       (SELECT r.id FROM roles r WHERE r.id = (x.opt->>'role_id')::bigint AND r.guild_id = t.guild_id)
  FROM event_templates t
 CROSS JOIN LATERAL jsonb_array_elements(t.options_json) WITH ORDINALITY x (opt, pos)
  JOIN option_library l ON l.guild_id = t.guild_id AND lower(l.name) = lower(trim(x.opt->>'name'));
ALTER TABLE event_templates DROP COLUMN options_json;
